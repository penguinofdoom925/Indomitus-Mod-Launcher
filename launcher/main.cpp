// spec: "embedded" -> WAVE resource compiled into the exe (ids in launcher.rc),
//       "none" / "" -> silent, anything else -> path to a .wav file.
static void PlaySoundSpec(const std::wstring& spec, int resourceId)
{
    if (spec.empty() || _wcsicmp(spec.c_str(), L"none") == 0) return;
    if (_wcsicmp(spec.c_str(), L"embedded") == 0) {
        PlaySoundW(MAKEINTRESOURCEW(resourceId), GetModuleHandleW(nullptr), SND_RESOURCE | SND_ASYNC | SND_NODEFAULT);
        return;
    }
    PlaySoundW(spec.c_str(), nullptr, SND_FILENAME | SND_ASYNC | SND_NODEFAULT);
}
