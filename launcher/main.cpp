static FILE* g_log = nullptr;
static bool  g_console = false;

static std::string Utf8(const std::wstring& w)
{
    if (w.empty()) return "";
    int n = WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), nullptr, 0, nullptr, nullptr);
    std::string s(n, 0);
    WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), &s[0], n, nullptr, nullptr);
    return s;
}

static std::wstring Widen(const std::string& s)
{
    if (s.empty()) return L"";
    int n = MultiByteToWideChar(CP_UTF8, 0, s.c_str(), (int)s.size(), nullptr, 0);
    std::wstring w(n, 0);
    MultiByteToWideChar(CP_UTF8, 0, s.c_str(), (int)s.size(), &w[0], n);
    return w;
}

static std::wstring Format(const wchar_t* fmt, va_list ap)
{
    wchar_t buf[2048];
    int n = _vsnwprintf(buf, 2047, fmt, ap);
    if (n < 0) n = 2047;
    buf[n] = 0;
    return buf;
}

static void Log(const wchar_t* fmt, ...)
{
    va_list ap; va_start(ap, fmt);
    std::wstring msg = Format(fmt, ap);
    va_end(ap);

    SYSTEMTIME st; GetLocalTime(&st);
    wchar_t ts[32];
    swprintf(ts, 32, L"[%02d:%02d:%02d.%03d] ", st.wHour, st.wMinute, st.wSecond, st.wMilliseconds);
    std::wstring line = ts + msg + L"\n";

    if (g_console) wprintf(L"%ls", line.c_str());
    if (g_log) {
        std::string u = Utf8(line);
        fwrite(u.data(), 1, u.size(), g_log);
        fflush(g_log);
    }
}

static int Fail(int code, const wchar_t* fmt, ...)
{
    va_list ap; va_start(ap, fmt);
    std::wstring msg = Format(fmt, ap);
    va_end(ap);
    Log(L"ERROR: %ls", msg.c_str());
    MessageBoxW(nullptr, (msg + L"\n\nSee gem_launcher.log for details.").c_str(), L"Indomitus", MB_ICONERROR | MB_OK);
    return code;
}

static std::wstring LastErrorText(DWORD err = GetLastError())
{
    wchar_t* msg = nullptr;
    FormatMessageW(FORMAT_MESSAGE_ALLOCATE_BUFFER | FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS,
                   nullptr, err, 0, (LPWSTR)&msg, 0, nullptr);
    std::wstring s = msg ? msg : L"";
    if (msg) LocalFree(msg);
    while (!s.empty() && (s.back() == L'\r' || s.back() == L'\n')) s.pop_back();
    wchar_t code[32];
    swprintf(code, 32, L" (0x%08X)", err);
    return s + code;
}

