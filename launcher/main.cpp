static void Star(HDC dc, int cx, int cy, int r, COLORREF c)
{
    POINT pts[10];
    for (int i = 0; i < 10; ++i) {
        double a = -1.5707963 + i * 0.6283185;
        double rr = (i % 2 == 0) ? r : r * 0.4;
        pts[i] = { cx + (int)(cos(a) * rr + 0.5), cy + (int)(sin(a) * rr + 0.5) };
    }
    PolyC(dc, pts, 10, c);
}

