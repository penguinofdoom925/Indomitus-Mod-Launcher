// ================================================================ profile mods

// <profiles>\<id>\options.set holds
//   {mods
//       "folder_name:0"
//   }
// This makes sure the configured mods are in that list before the game starts.
// The game keeps <profiles> in one of two places, depending on the PC:
//   Documents\my games\gates of hell\profiles
//   %LocalAppData%\digitalmindsoft\gates of hell\profiles
// Both are searched; the most recently written options.set wins (= the profile the game uses now).

static std::vector<std::wstring> ProfilesDirs()
{
    std::vector<std::wstring> out;
    wchar_t p[MAX_PATH];
    if (SUCCEEDED(SHGetFolderPathW(nullptr, CSIDL_PERSONAL, nullptr, SHGFP_TYPE_CURRENT, p)))
        out.push_back(std::wstring(p) + L"\\my games\\gates of hell\\profiles");
    if (SUCCEEDED(SHGetFolderPathW(nullptr, CSIDL_LOCAL_APPDATA, nullptr, SHGFP_TYPE_CURRENT, p)))
        out.push_back(std::wstring(p) + L"\\digitalmindsoft\\gates of hell\\profiles");
    return out;
}

// For log and error messages: every place that was searched.
static std::wstring ProfilesDirsText()
{
    std::wstring s;
    for (const auto& d : ProfilesDirs()) { if (!s.empty()) s += L" ; "; s += d; }
    return s;
}

static std::wstring FindOptionsSet(const Config& cfg)
{
    std::wstring best; FILETIME bestTime{};
    auto consider = [&](const std::wstring& opt) {
        WIN32_FILE_ATTRIBUTE_DATA a{};
        if (!GetFileAttributesExW(opt.c_str(), GetFileExInfoStandard, &a) || (a.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY)) return;
        if (best.empty() || CompareFileTime(&a.ftLastWriteTime, &bestTime) > 0) { best = opt; bestTime = a.ftLastWriteTime; }
    };
    for (const auto& base : ProfilesDirs()) {
        if (!cfg.modsProfile.empty()) { consider(base + L"\\" + cfg.modsProfile + L"\\options.set"); continue; }
        WIN32_FIND_DATAW fd;
        HANDLE h = FindFirstFileW((base + L"\\*").c_str(), &fd);
        if (h == INVALID_HANDLE_VALUE) continue;
        do {
            if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) || fd.cFileName[0] == L'.') continue;
            consider(base + L"\\" + fd.cFileName + L"\\options.set");
        } while (FindNextFileW(h, &fd));
        FindClose(h);
    }
    if (!best.empty()) Log(L"profile: %ls", best.c_str());
    return best;
}

static bool WriteFileA(const std::wstring& path, const std::string& data)
{
    HANDLE h = CreateFileW(path.c_str(), GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (h == INVALID_HANDLE_VALUE) return false;
    DWORD w = 0;
    bool ok = WriteFile(h, data.data(), (DWORD)data.size(), &w, nullptr) && w == data.size();
    CloseHandle(h);
    return ok;
}

// Replaces a file without ever leaving it empty or half-written: write <path>.tmp, flush it to disk,
// then swap it in with one rename. A crash or kill mid-way leaves either the old or the new file.
static bool WriteFileAtomic(const std::wstring& path, const std::string& data)
{
    std::wstring tmp = path + L".launcher-tmp";
    HANDLE h = CreateFileW(tmp.c_str(), GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, nullptr);
    if (h == INVALID_HANDLE_VALUE) return false;
    DWORD w = 0;
    bool ok = WriteFile(h, data.data(), (DWORD)data.size(), &w, nullptr) && w == data.size() && FlushFileBuffers(h);
    CloseHandle(h);
    if (ok) ok = MoveFileExW(tmp.c_str(), path.c_str(), MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH) != FALSE;
    if (!ok) DeleteFileW(tmp.c_str());
    return ok;
}

// One-time copy of the profile as it was before the launcher first touched it. Required: no backup, no edit.
static bool EnsureProfileBackup(const std::wstring& opt, const std::string& text, std::wstring& err)
{
    std::wstring bak = opt + L".launcher-backup";
    if (PathFileExistsW(bak.c_str())) return true;
    if (WriteFileAtomic(bak, text)) { Log(L"profile backup written: %ls", bak.c_str()); return true; }
    err = L"could not write the backup " + bak + L" - the profile was not changed";
    return false;
}

// ---- which mods: every mod whose mod.info has the marker in its {desc "..."}
// The game lists mods in options.set by these names (game.log "Mod: activate mod ..."):
//   <game>\mods\<Folder>\mod.info                                 -> "<folder>"    (lower case)
//   <library>\steamapps\workshop\content\<appid>\<id>\mod.info     -> "mod_<id>"   (Steam Workshop)

static std::string AsciiLower(std::string s)
{
    for (auto& c : s) if (c >= 'A' && c <= 'Z') c = (char)(c - 'A' + 'a');
    return s;
}

// Loose form used to compare the marker with a description: lower case, and every ASCII character
// that is not a letter or digit ([ ] _ - . , spaces, ...) becomes one space, with a space at each end.
// So "[INDOMITUS_MOD_LAUNCHER]", "INDOMITUS MOD LAUNCHER" and "indomitus-mod-launcher" are the same
// text, and the marker only matches whole words ("indomitus mod launchers" does not match).
static std::string MarkerKey(const std::string& s)
{
    std::string k = " ";
    for (char ch : AsciiLower(s)) {
        unsigned char c = (unsigned char)ch;
        bool word = c >= 0x80 || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9');   // >= 0x80: UTF-8 letters
        if (word) k += ch;
        else if (k.back() != ' ') k += ' ';
    }
    if (k.back() != ' ') k += ' ';
    return k;
}

// markerKey: MarkerKey() of the marker.
static bool ModInfoHasMarker(const std::wstring& modInfo, const std::string& markerKey)
{
    std::string t = ReadFileA(modInfo);
    if (t.size() >= 2 && (unsigned char)t[0] == 0xFF && (unsigned char)t[1] == 0xFE) {   // UTF-16 LE file
        std::wstring w;
        for (size_t i = 2; i + 1 < t.size(); i += 2) w += (wchar_t)((unsigned char)t[i] | ((unsigned char)t[i + 1] << 8));
        t = Utf8(w);
    }
    for (size_t p = 0; (p = t.find("{desc", p)) != std::string::npos; p += 5) {
        size_t q1 = p + 5;
        while (q1 < t.size() && (t[q1] == ' ' || t[q1] == '\t' || t[q1] == '\r' || t[q1] == '\n')) ++q1;
        if (q1 >= t.size() || t[q1] != '"') continue;              // "{description" or similar, not {desc "..."}
        size_t q2 = t.find('"', q1 + 1);
        if (q2 == std::string::npos) break;
        if (MarkerKey(t.substr(q1 + 1, q2 - q1 - 1)).find(markerKey) != std::string::npos) return true;
    }
    return false;
}

static void ScanMarkedMods(const std::wstring& dir, const wchar_t* prefix, const std::string& markerKey, std::vector<std::wstring>& out)
{
    WIN32_FIND_DATAW fd;
    HANDLE h = FindFirstFileW((dir + L"\\*").c_str(), &fd);
    if (h == INVALID_HANDLE_VALUE) return;
    do {
        if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) || fd.cFileName[0] == L'.') continue;
        std::wstring name = fd.cFileName;
        bool valid = true;   // the game rejects folder names like "- bckp"; never put those in the profile
        for (wchar_t c : name) if (!(iswalnum(c) || c == L'_' || c == L'-')) { valid = false; break; }
        if (!valid) continue;
        std::wstring info = dir + L"\\" + name + L"\\mod.info";
        if (!PathFileExistsW(info.c_str()) || !ModInfoHasMarker(info, markerKey)) continue;
        std::wstring entry = prefix + name;
        for (auto& c : entry) c = towlower(c);
        out.push_back(entry);
        Log(L"marked mod: %ls  (%ls)", entry.c_str(), info.c_str());
    } while (FindNextFileW(h, &fd));
    FindClose(h);
}

// Local mods and Steam Workshop mods carrying the marker, sorted alphabetically (= the order they are enabled in).
static std::vector<std::wstring> FindMarkedMods(const std::wstring& gameExe, const std::wstring& appid, const std::wstring& marker)
{
    std::vector<std::wstring> out;
    std::string m = MarkerKey(Utf8(marker));
    if (m == " ") return out;                                                // empty (or only brackets) = no marker
    std::wstring root = DirOf(DirOf(DirOf(gameExe)));                       // binaries\x64\exe -> game root
    ScanMarkedMods(root + L"\\mods", L"", m, out);
    ScanMarkedMods(DirOf(DirOf(root)) + L"\\workshop\\content\\" + appid, L"mod_", m, out);   // <library>\steamapps\...
    for (size_t i = 1; i < out.size(); ++i)
        for (size_t j = i; j > 0 && _wcsicmp(out[j].c_str(), out[j - 1].c_str()) < 0; --j) std::swap(out[j], out[j - 1]);
    for (size_t i = 1; i < out.size(); )
        if (_wcsicmp(out[i].c_str(), out[i - 1].c_str()) == 0) out.erase(out.begin() + i); else ++i;
    return out;
}

// Returns true when the profile is ready (already fine or updated). err gets a message otherwise.
static bool EnsureModsEnabled(const Config& cfg, std::wstring& err)
{
    // Scan again now: mod.info files may have changed since the launcher opened.
    const std::vector<std::wstring> mods = FindMarkedMods(cfg.exe, cfg.appid, cfg.modsMarker);
    if (mods.empty()) { Log(L"no marked mods - the profile mod list is left alone"); return true; }
    std::wstring opt = FindOptionsSet(cfg);
    if (opt.empty() || !PathFileExistsW(opt.c_str())) {
        // Fresh install: the game creates its profile on the first start. Don't block that start.
        Log(L"no profile options.set under %ls yet - starting without changing the mod list", ProfilesDirsText().c_str());
        MessageBoxW(nullptr, L"This looks like the first start of Gates of Hell on this PC - the game has no profile yet,\n"
                             L"so the Indomitus mods can't be switched on for this run.\n\n"
                             L"Let the game reach the main menu, quit, and start it again from this launcher.",
                    L"Indomitus", MB_ICONINFORMATION | MB_OK);
        return true;
    }
    std::string text = ReadFileA(opt);
    if (text.empty()) { err = L"could not read " + opt; return false; }

    size_t start = std::string::npos, pos = 0;
    while ((pos = text.find("{mods", pos)) != std::string::npos) {
        char after = pos + 5 < text.size() ? text[pos + 5] : ' ';
        if (after == '\r' || after == '\n' || after == ' ' || after == '\t' || after == '}') { start = pos; break; }
        pos += 5;
    }
    std::vector<std::string> entries;
    size_t end = std::string::npos;
    if (start != std::string::npos) {
        int depth = 0;
        for (size_t i = start; i < text.size(); ++i) {
            if (text[i] == '{') ++depth;
            else if (text[i] == '}' && --depth == 0) { end = i + 1; break; }
        }
        if (end == std::string::npos) { err = L"unbalanced {mods} block in " + opt; return false; }
        for (size_t q = text.find('"', start); q != std::string::npos && q < end; q = text.find('"', q + 1)) {
            size_t q2 = text.find('"', q + 1);
            if (q2 == std::string::npos || q2 > end) break;
            entries.push_back(text.substr(q + 1, q2 - q - 1));
            q = q2;
        }
    }

    auto nameOf = [](const std::string& e) { size_t c = e.find(':'); return c == std::string::npos ? e : e.substr(0, c); };
    auto same = [](const std::string& a, const std::string& b) { return _stricmp(a.c_str(), b.c_str()) == 0; };

    std::vector<std::string> wanted;
    for (const auto& m : mods) wanted.push_back(Utf8(m));

    // Other mods keep their places (unless exclusive); the marked ones follow, in alphabetical order. An existing
    // entry keeps its ":n" suffix.
    std::vector<std::string> result;
    if (!cfg.modsExclusive)
        for (const auto& e : entries) {
            bool marked = false;
            for (const auto& w : wanted) if (same(nameOf(e), w)) { marked = true; break; }
            if (!marked) result.push_back(e);
        }
    for (const auto& w : wanted) {
        std::string keep = w + ":0";
        for (const auto& e : entries) if (same(nameOf(e), w)) { keep = e; break; }
        result.push_back(keep);
    }
    if (result == entries) { Log(L"profile mods already as required (%ls)", opt.c_str()); return true; }

    std::string block = "\t{mods\r\n";
    for (const auto& e : result) block += "\t\t\"" + e + "\"\r\n";
    block += "\t}";

    std::string out;
    if (start != std::string::npos) out = text.substr(0, start - (start > 0 && text[start - 1] == '\t' ? 1 : 0)) + block + text.substr(end);
    else {
        size_t last = text.rfind('}');
        if (last == std::string::npos) { err = L"unexpected options.set layout"; return false; }
        out = text.substr(0, last) + block + "\r\n" + text.substr(last);
    }

    if (!EnsureProfileBackup(opt, text, err)) return false;
    if (!WriteFileAtomic(opt, out)) { err = L"could not write " + opt; return false; }
    std::wstring list;
    for (const auto& e : result) { if (!list.empty()) list += L", "; list += Widen(e); }
    Log(L"profile mods updated: %ls  ->  %ls", opt.c_str(), list.c_str());
    return true;
}

// ---- ability hotkeys
// The mod's ability buttons name a key slot ({Key "actions/melee_toggle"} in resource\interface\action\*.set), and the game
// only reads slots from the player's own <profile>\keys.set: defaults shipped inside a mod are ignored, so until now every
// player had to add the lines by hand. Before each launch the slots listed in hotkeys= that are MISSING from keys.set are
// added with their default key. A slot that is already there is never touched, whatever it is bound to (the player's own
// choice, or cleared on purpose with {value ""}). A one-time keys.set.launcher-backup is kept. Never blocks the launch.
//   {keys
//       {"actions/jetpack"
//           {value "DOUBLE + KEY_J"}
//       }
//   }
static void EnsureHotkeys(const Config& cfg)
{
    if (cfg.hotkeys.empty()) return;
    std::wstring opt = FindOptionsSet(cfg);
    if (opt.empty()) return;                                   // no profile yet (first start): next launch
    size_t slash = opt.find_last_of(L'\\');
    if (slash == std::wstring::npos) return;
    std::wstring keys = opt.substr(0, slash) + L"\\keys.set";
    if (!PathFileExistsW(keys.c_str())) { Log(L"hotkeys: no %ls yet - nothing added", keys.c_str()); return; }
    std::string text = ReadFileA(keys);
    size_t open = text.find("{keys"), last = text.rfind('}');
    if (text.empty() || open == std::string::npos || last == std::string::npos || last < open) {
        Log(L"hotkeys: unexpected layout in %ls - left alone", keys.c_str());
        return;
    }
    const char* nl = text.find("\r\n") != std::string::npos ? "\r\n" : "\n";

    std::string add; std::wstring added;
    const std::string list = Utf8(cfg.hotkeys);
    for (size_t a = 0; a < list.size();) {
        size_t b = list.find(';', a);
        if (b == std::string::npos) b = list.size();
        std::string item = list.substr(a, b - a);
        a = b + 1;
        size_t eq = item.find('=');
        if (eq == std::string::npos) continue;
        auto trim = [](std::string v) {
            size_t i = v.find_first_not_of(" \t"), j = v.find_last_not_of(" \t");
            return i == std::string::npos ? std::string() : v.substr(i, j - i + 1);
        };
        std::string name = trim(item.substr(0, eq)), value = trim(item.substr(eq + 1));
        if (name.empty() || value.empty() || name.find('"') != std::string::npos || value.find('"') != std::string::npos) continue;
        // present already? the slot name in quotes, any case
        std::string hay = AsciiLower(text), needle = "\"" + AsciiLower(name) + "\"";
        if (hay.find(needle) != std::string::npos) continue;
        bool quote = value.find(' ') != std::string::npos || value.find('+') != std::string::npos;
        add += std::string("\t{\"") + name + "\"" + nl + "\t\t{value " + (quote ? "\"" + value + "\"" : value) + "}" + nl + "\t}" + nl;
        if (!added.empty()) added += L", ";
        added += Widen(name) + L" = " + Widen(value);
    }
    if (add.empty()) { Log(L"hotkeys: all ability keys already in %ls", keys.c_str()); return; }

    // the new lines go right before the closing brace of {keys}, on a line of their own
    std::string head = text.substr(0, last);
    if (!head.empty() && head.back() != '\n') head += nl;
    std::string out = head + add + text.substr(last);
    std::wstring err;
    if (!EnsureProfileBackup(keys, text, err)) { Log(L"hotkeys: %ls", err.c_str()); return; }
    if (!WriteFileAtomic(keys, out)) { Log(L"hotkeys: could not write %ls - nothing added", keys.c_str()); return; }
    Log(L"hotkeys added to %ls: %ls", keys.c_str(), added.c_str());
}

// Removes the configured mods from the profile list so a plain Steam start runs vanilla.
static bool DisableRequiredMods(const Config& cfg, std::wstring& err, int& removed)
{
    removed = 0;
    const std::vector<std::wstring> mods = FindMarkedMods(cfg.exe, cfg.appid, cfg.modsMarker);   // current mod.info files
    if (mods.empty()) return true;
    std::wstring opt = FindOptionsSet(cfg);
    if (opt.empty() || !PathFileExistsW(opt.c_str())) { err = L"profile options.set not found in " + ProfilesDirsText(); return false; }
    std::string text = ReadFileA(opt);
    if (text.empty()) { err = L"could not read " + opt; return false; }

    size_t start = std::string::npos, pos = 0;
    while ((pos = text.find("{mods", pos)) != std::string::npos) {
        char after = pos + 5 < text.size() ? text[pos + 5] : ' ';
        if (after == '\r' || after == '\n' || after == ' ' || after == '\t' || after == '}') { start = pos; break; }
        pos += 5;
    }
    if (start == std::string::npos) return true;   // no mods block at all = nothing enabled
    int depth = 0; size_t end = std::string::npos;
    for (size_t i = start; i < text.size(); ++i) {
        if (text[i] == '{') ++depth;
        else if (text[i] == '}' && --depth == 0) { end = i + 1; break; }
    }
    if (end == std::string::npos) { err = L"unbalanced {mods} block"; return false; }

    std::vector<std::string> entries, kept;
    for (size_t q = text.find('"', start); q != std::string::npos && q < end; q = text.find('"', q + 1)) {
        size_t q2 = text.find('"', q + 1);
        if (q2 == std::string::npos || q2 > end) break;
        entries.push_back(text.substr(q + 1, q2 - q - 1));
        q = q2;
    }
    for (const auto& e : entries) {
        std::string name = e.substr(0, e.find(':'));
        bool drop = false;
        for (const auto& m : mods) if (_stricmp(name.c_str(), Utf8(m).c_str()) == 0) { drop = true; break; }
        if (drop) ++removed; else kept.push_back(e);
    }
    if (removed == 0) return true;

    std::string block = "\t{mods\r\n";
    for (const auto& e : kept) block += "\t\t\"" + e + "\"\r\n";
    block += "\t}";
    std::string out = text.substr(0, start - (start > 0 && text[start - 1] == '\t' ? 1 : 0)) + block + text.substr(end);
    if (!EnsureProfileBackup(opt, text, err)) return false;
    if (!WriteFileAtomic(opt, out)) { err = L"could not write " + opt; return false; }
    Log(L"profile mods disabled: removed %d entr%ls from %ls", removed, removed == 1 ? L"y" : L"ies", opt.c_str());
    return true;
}

// ================================================================ PE helpers

static WORD PeMachine(const std::wstring& path)
{
    std::ifstream f(std::filesystem::path(path), std::ios::binary);
    if (!f) return 0;
    IMAGE_DOS_HEADER dos{};
    f.read((char*)&dos, sizeof(dos));
    if (dos.e_magic != IMAGE_DOS_SIGNATURE) return 0;
    f.seekg(dos.e_lfanew, std::ios::beg);
    DWORD sig = 0;
    f.read((char*)&sig, sizeof(sig));
    if (sig != IMAGE_NT_SIGNATURE) return 0;
    IMAGE_FILE_HEADER fh{};
    f.read((char*)&fh, sizeof(fh));
    return fh.Machine;
}

