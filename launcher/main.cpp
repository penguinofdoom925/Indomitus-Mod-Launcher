static void CreateFonts()
{
    for (HFONT* f : { &g_fTitle, &g_fSub, &g_fButton, &g_fSmall, &g_fSmallB }) if (*f) DeleteObject(*f);
    // Title always in the embedded face; the rest follows the language file's font= (if any).
    // With no font= the embedded face is used - unless it lacks letters this language needs
    // (Gothicha has no accented or non-Latin letters), then the whole UI uses Segoe UI so words
    // are never drawn in two fonts.
    std::wstring langFont = g_langMeta[g_lang].font;
    if (langFont.empty()) {
        langFont = g_titleFace;
        HDC sdc = GetDC(nullptr);
        HFONT probe = MakeFont(langFont.c_str(), 12, FW_NORMAL);
        HGDIOBJ old = SelectObject(sdc, probe);
        bool ok = true;
        for (const auto& kv : g_langCur) {
            const std::wstring& v = kv.second;
            if (v.empty() || !_wcsicmp(kv.first.c_str(), L"name") || !_wcsicmp(kv.first.c_str(), L"font")) continue;
            std::vector<WORD> types(v.size()), glyphs(v.size());
            GetStringTypeW(CT_CTYPE1, v.c_str(), (int)v.size(), types.data());
            GetGlyphIndicesW(sdc, v.c_str(), (int)v.size(), glyphs.data(), GGI_MARK_NONEXISTING_GLYPHS);
            for (size_t k = 0; k < v.size(); ++k) if ((types[k] & C1_ALPHA) && glyphs[k] == 0xFFFF) { ok = false; break; }
            if (!ok) break;
        }
        SelectObject(sdc, old); DeleteObject(probe); ReleaseDC(nullptr, sdc);
        if (!ok) { langFont = L"Segoe UI"; Log(L"ui font: %ls lacks letters for '%ls', using Segoe UI", g_titleFace.c_str(), kLangs[g_lang].code); }
    }
    g_uiFaceIsTitle = (langFont == g_titleFace);
    for (int i = 0; i < kLangCount; ++i) {
        if (g_fLang[i]) DeleteObject(g_fLang[i]);
        g_fLang[i] = MakeFont(g_langMeta[i].font.empty() ? L"Segoe UI" : g_langMeta[i].font.c_str(), 10, FW_NORMAL);
    }
    const wchar_t* face = langFont.c_str();
    g_fTitle  = MakeFont(g_titleFace.c_str(), g_cfg.titleSize, FW_NORMAL);
    g_fSub    = MakeFont(face, 11, FW_NORMAL);
    g_fButton = MakeFont(face, g_uiFaceIsTitle ? 14 : 13, g_uiFaceIsTitle ? FW_NORMAL : FW_SEMIBOLD);
    g_fSmall  = MakeFont(face,  9, FW_NORMAL);
    g_fSmallB = MakeFont(face,  9, FW_NORMAL);
}

// Reads the BITMAP resource ourselves (LoadImage rejects V4/V5 + BITFIELDS files that image
// editors produce) and converts it to a 32bpp premultiplied DIB. 24-bit or alpha-less files get
// their background keyed out from the top-left pixel colour.
static void LoadLogo()
{
    HMODULE hi = GetModuleHandleW(nullptr);
    HRSRC r = FindResourceW(hi, MAKEINTRESOURCEW(RES_LOGO), RT_BITMAP);
    HGLOBAL g = r ? LoadResource(hi, r) : nullptr;
    const BYTE* p = g ? (const BYTE*)LockResource(g) : nullptr;
    DWORD size = r ? SizeofResource(hi, r) : 0;
    if (!p || size < 40) { Log(L"logo: no resource"); return; }

    auto u32 = [&](DWORD o) -> DWORD { return o + 4 <= size ? *(const DWORD*)(p + o) : 0; };
    auto u16 = [&](DWORD o) -> WORD  { return o + 2 <= size ? *(const WORD*)(p + o) : 0; };
    DWORD hdr = u32(0);
    int w = (int)u32(4), h = (int)u32(8);
    WORD bpp = u16(14); DWORD comp = u32(16);
    bool topDown = h < 0; if (topDown) h = -h;
    if (w <= 0 || h <= 0 || (bpp != 24 && bpp != 32) || (comp != 0 /*BI_RGB*/ && comp != 3 /*BI_BITFIELDS*/)) {
        Log(L"logo: unsupported bmp (hdr %u, %dx%d, %u bpp, comp %u) - use 24/32-bit uncompressed", hdr, w, h, bpp, comp); return;
    }
    DWORD rMask = 0x00FF0000, gMask = 0x0000FF00, bMask = 0x000000FF, aMask = (bpp == 32) ? 0xFF000000 : 0;
    DWORD dataOff = hdr;
    if (comp == 3) {
        if (hdr >= 52) { rMask = u32(40); gMask = u32(44); bMask = u32(48); aMask = hdr >= 56 ? u32(52) : 0; }
        else { rMask = u32(40); gMask = u32(44); bMask = u32(48); dataOff = hdr + 12; }
    }
    DWORD clrUsed = u32(32);
    dataOff += clrUsed * 4;
    DWORD stride = ((w * bpp + 31) / 32) * 4;
    if (dataOff + stride * (DWORD)h > size) { Log(L"logo: truncated bitmap"); return; }

    auto shiftOf = [](DWORD m) { int s = 0; if (!m) return 0; while (!(m & 1)) { m >>= 1; ++s; } return s; };
    auto bitsOf  = [](DWORD m) { int n = 0; while (m) { n += m & 1; m >>= 1; } return n; };
    auto chan = [&](DWORD px, DWORD mask) -> BYTE {
        if (!mask) return 0;
        int sh = shiftOf(mask), nb = bitsOf(mask);
        DWORD v = (px & mask) >> sh;
        return nb >= 8 ? (BYTE)(v >> (nb - 8)) : (BYTE)(v * 255 / ((1u << nb) - 1));
    };

    // first pass: does the file carry a usable alpha channel?
    bool hasAlpha = false;
    if (aMask) {
        for (int y = 0; y < h && !hasAlpha; ++y) {
            const BYTE* row = p + dataOff + (DWORD)y * stride;
            for (int x = 0; x < w; ++x) if (chan(*(const DWORD*)(row + x * 4), aMask) != 0 && chan(*(const DWORD*)(row + x * 4), aMask) != 255) { hasAlpha = true; break; }
        }
        if (!hasAlpha) {   // all 0 or all 255: check for a mix of 0 and 255 (hard-edged alpha)
            bool saw0 = false, saw255 = false;
            for (int y = 0; y < h && !(saw0 && saw255); ++y) {
                const BYTE* row = p + dataOff + (DWORD)y * stride;
                for (int x = 0; x < w; ++x) { BYTE a = chan(*(const DWORD*)(row + x * 4), aMask); if (a == 0) saw0 = true; else saw255 = true; if (saw0 && saw255) break; }
            }
            hasAlpha = saw0 && saw255;
        }
    }

    g_logoPx.assign((size_t)w * h, 0);
    DWORD* bits = g_logoPx.data();

    // key colour for alpha-less files: top-left pixel
    const BYTE* row0 = p + dataOff + (DWORD)(topDown ? 0 : h - 1) * stride;
    BYTE kr, kg, kb;
    if (bpp == 32) { DWORD px = *(const DWORD*)row0; kr = chan(px, rMask); kg = chan(px, gMask); kb = chan(px, bMask); }
    else { kb = row0[0]; kg = row0[1]; kr = row0[2]; }

    DWORD* out = (DWORD*)bits;
    for (int y = 0; y < h; ++y) {
        int srcY = topDown ? y : (h - 1 - y);
        const BYTE* row = p + dataOff + (DWORD)srcY * stride;
        for (int x = 0; x < w; ++x) {
            BYTE rr, gg, bb, aa;
            if (bpp == 32) { DWORD px = *(const DWORD*)(row + x * 4); rr = chan(px, rMask); gg = chan(px, gMask); bb = chan(px, bMask); aa = hasAlpha ? chan(px, aMask) : 255; }
            else { bb = row[x * 3]; gg = row[x * 3 + 1]; rr = row[x * 3 + 2]; aa = 255; }
            if (!hasAlpha) {
                int d = abs(rr - kr); if (abs(gg - kg) > d) d = abs(gg - kg); if (abs(bb - kb) > d) d = abs(bb - kb);
                aa = (BYTE)(d * 4 > 255 ? 255 : d * 4);   // soft key: within ~64 levels of the corner colour fades out
            }
            out[(size_t)y * w + x] = (DWORD)aa << 24 | (DWORD)(rr * aa / 255) << 16 | (DWORD)(gg * aa / 255) << 8 | (DWORD)(bb * aa / 255);
        }
    }
    g_logoSrcW = w; g_logoSrcH = h;
    Log(L"logo: %dx%d, %u bpp, alpha %ls", w, h, bpp, hasAlpha ? L"from file" : L"keyed from corner colour");
}

// Resamples the source into a DIB of exactly tw x th (area-average when shrinking, bilinear when
// enlarging) so AlphaBlend never has to stretch. Cached until the target size changes.
static HBITMAP ScaledLogo(int tw, int th)
{
    if (g_logoPx.empty() || tw <= 0 || th <= 0) return nullptr;
    if (g_logo && g_logoW == tw && g_logoH == th) return g_logo;
    if (g_logo) { DeleteObject(g_logo); g_logo = nullptr; }

    BITMAPINFO bi{}; bi.bmiHeader.biSize = sizeof(BITMAPINFOHEADER);
    bi.bmiHeader.biWidth = tw; bi.bmiHeader.biHeight = -th; bi.bmiHeader.biPlanes = 1; bi.bmiHeader.biBitCount = 32; bi.bmiHeader.biCompression = BI_RGB;
    void* bitsV = nullptr;
    HBITMAP dib = CreateDIBSection(nullptr, &bi, DIB_RGB_COLORS, &bitsV, nullptr, 0);
    if (!dib || !bitsV) return nullptr;
    DWORD* out = (DWORD*)bitsV;
    const int sw = g_logoSrcW, sh = g_logoSrcH;
    const DWORD* src = g_logoPx.data();
    const double sx = (double)sw / tw, sy = (double)sh / th;

    for (int y = 0; y < th; ++y) {
        for (int x = 0; x < tw; ++x) {
            double acc[4] = { 0, 0, 0, 0 }, wsum = 0;
            if (sx > 1.0 || sy > 1.0) {
                // box filter over the source footprint
                double x0 = x * sx, x1 = (x + 1) * sx, y0 = y * sy, y1 = (y + 1) * sy;
                for (int yy = (int)y0; yy < (int)ceil(y1) && yy < sh; ++yy) {
                    double fy = (yy + 1 < y1 ? yy + 1 : y1) - (yy > y0 ? yy : y0); if (fy <= 0) continue;
                    for (int xx = (int)x0; xx < (int)ceil(x1) && xx < sw; ++xx) {
                        double fx = (xx + 1 < x1 ? xx + 1 : x1) - (xx > x0 ? xx : x0); if (fx <= 0) continue;
                        double wgt = fx * fy; DWORD px = src[(size_t)yy * sw + xx];
                        acc[0] += (px & 255) * wgt; acc[1] += ((px >> 8) & 255) * wgt; acc[2] += ((px >> 16) & 255) * wgt; acc[3] += (px >> 24) * wgt; wsum += wgt;
                    }
                }
            } else {
                // bilinear
                double fx = (x + 0.5) * sx - 0.5, fy = (y + 0.5) * sy - 0.5;
                int ix = (int)floor(fx), iy = (int)floor(fy);
                double ax = fx - ix, ay = fy - iy;
                for (int dy = 0; dy < 2; ++dy) for (int dx = 0; dx < 2; ++dx) {
                    int xx = ix + dx, yy = iy + dy;
                    if (xx < 0) xx = 0; if (yy < 0) yy = 0; if (xx >= sw) xx = sw - 1; if (yy >= sh) yy = sh - 1;
                    double wgt = (dx ? ax : 1 - ax) * (dy ? ay : 1 - ay); DWORD px = src[(size_t)yy * sw + xx];
                    acc[0] += (px & 255) * wgt; acc[1] += ((px >> 8) & 255) * wgt; acc[2] += ((px >> 16) & 255) * wgt; acc[3] += (px >> 24) * wgt; wsum += wgt;
                }
            }
            if (wsum <= 0) { out[(size_t)y * tw + x] = 0; continue; }
            DWORD b = (DWORD)(acc[0] / wsum + 0.5), g = (DWORD)(acc[1] / wsum + 0.5), r = (DWORD)(acc[2] / wsum + 0.5), a = (DWORD)(acc[3] / wsum + 0.5);
            if (b > a) b = a; if (g > a) g = a; if (r > a) r = a;   // keep premultiplied invariant
            out[(size_t)y * tw + x] = a << 24 | r << 16 | g << 8 | b;
        }
    }
    g_logo = dib; g_logoW = tw; g_logoH = th;
    return dib;
}

