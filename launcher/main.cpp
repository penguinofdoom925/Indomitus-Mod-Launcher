static std::wstring g_titleFace;

// Candidate face names from a TTF/OTF blob: name IDs 1 (family, what GDI uses), 16
// (typographic family) and 4 (full name), Windows platform, en-US preferred.
static std::vector<std::wstring> TtfNameCandidates(const BYTE* p, DWORD size)
{
    std::vector<std::wstring> out;
    auto u16 = [&](DWORD o) -> DWORD { return o + 2 <= size ? (DWORD)((p[o] << 8) | p[o + 1]) : 0; };
    auto u32 = [&](DWORD o) -> DWORD { return o + 4 <= size ? (DWORD)((p[o] << 24) | (p[o + 1] << 16) | (p[o + 2] << 8) | p[o + 3]) : 0; };
    DWORD numTables = u16(4);
    for (DWORD t = 0; t < numTables; ++t) {
        DWORD rec = 12 + t * 16;
        if (rec + 16 > size) break;
        if (memcmp(p + rec, "name", 4) != 0) continue;
        DWORD nameOff = u32(rec + 8), count = u16(nameOff + 2), strOff = nameOff + u16(nameOff + 4);
        std::wstring byId[17];
        for (DWORD i = 0; i < count; ++i) {
            DWORD r = nameOff + 6 + i * 12;
            DWORD platform = u16(r), lang = u16(r + 4), nameId = u16(r + 6), len = u16(r + 8), off = strOff + u16(r + 10);
            if (platform != 3 || nameId > 16 || off + len > size) continue;
            std::wstring w;
            for (DWORD k = 0; k + 1 < len; k += 2) w += (wchar_t)((p[off + k] << 8) | p[off + k + 1]);
            if (!w.empty() && (byId[nameId].empty() || lang == 0x409)) byId[nameId] = w;
        }
        for (int id : { 1, 16, 4 }) if (!byId[id].empty()) out.push_back(byId[id]);
        // also the family name with a trailing style word removed, as a last resort
        for (const wchar_t* t : { L" Regular", L" Book", L" Normal", L" Medium" }) {
            size_t tl = wcslen(t);
            if (byId[1].size() > tl && _wcsicmp(byId[1].c_str() + byId[1].size() - tl, t) == 0) out.push_back(byId[1].substr(0, byId[1].size() - tl));
        }
        break;
    }
    return out;
}

// What GDI really maps a face name to (an unknown name silently becomes a default font).
static std::wstring GdiResolves(const std::wstring& face)
{
    HDC dc = GetDC(nullptr);
    HFONT f = MakeFont(face.c_str(), 20, FW_NORMAL);
    HGDIOBJ old = SelectObject(dc, f);
    wchar_t got[LF_FACESIZE] = L"";
    GetTextFaceW(dc, LF_FACESIZE, got);
    SelectObject(dc, old); DeleteObject(f); ReleaseDC(nullptr, dc);
    return got;
}

static void LoadTitleFont()
{
    HMODULE hi = GetModuleHandleW(nullptr);
    std::vector<std::wstring> candidates;
    if (HRSRC r = FindResourceW(hi, MAKEINTRESOURCEW(RES_TITLE_FONT), RT_RCDATA)) {
        HGLOBAL g = LoadResource(hi, r);
        const BYTE* data = g ? (const BYTE*)LockResource(g) : nullptr;
        DWORD size = SizeofResource(hi, r), installed = 0;
        if (data && size && AddFontMemResourceEx((void*)data, size, nullptr, &installed)) {
            candidates = TtfNameCandidates(data, size);
            Log(L"embedded font loaded (%u face(s)); names in file: %u", installed, (unsigned)candidates.size());
        } else Log(L"embedded font could not be loaded: %ls", LastErrorText().c_str());
    }
    if (!g_cfg.titleFont.empty()) candidates.insert(candidates.begin(), g_cfg.titleFont);

    g_titleFace.clear();
    for (const auto& c : candidates) {
        std::wstring got = GdiResolves(c);
        Log(L"face \"%ls\" -> GDI \"%ls\"", c.c_str(), got.c_str());
        if (_wcsicmp(got.c_str(), c.c_str()) == 0) { g_titleFace = c; break; }
    }
    if (g_titleFace.empty()) { g_titleFace = L"Impact"; Log(L"no candidate matched, using Impact"); }
    Log(L"using face \"%ls\"", g_titleFace.c_str());
}

