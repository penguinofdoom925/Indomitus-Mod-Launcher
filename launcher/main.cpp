static std::vector<std::pair<std::wstring, std::wstring>> ParseKvText(std::string text)
{
    std::vector<std::pair<std::wstring, std::wstring>> out;
    if (text.size() >= 3 && (unsigned char)text[0] == 0xEF && (unsigned char)text[1] == 0xBB && (unsigned char)text[2] == 0xBF) text.erase(0, 3);
    size_t pos = 0;
    while (pos <= text.size()) {
        size_t nl = text.find('\n', pos); if (nl == std::string::npos) nl = text.size();
        std::string line = text.substr(pos, nl - pos); pos = nl + 1;
        while (!line.empty() && (line.back() == '\r' || line.back() == ' ' || line.back() == '\t')) line.pop_back();
        size_t f = line.find_first_not_of(" \t"); if (f == std::string::npos) continue;
        line = line.substr(f);
        if (line[0] == ';' || line[0] == '#' || line[0] == '[') continue;
        size_t eq = line.find('='); if (eq == std::string::npos) continue;
        std::string k = line.substr(0, eq), v = line.substr(eq + 1);
        while (!k.empty() && (k.back() == ' ' || k.back() == '\t')) k.pop_back();
        size_t vf = v.find_first_not_of(" \t"); v = vf == std::string::npos ? "" : v.substr(vf);
        out.push_back({ Widen(k), Widen(v) });
    }
    return out;
}

static std::string ResourceText(int id)
{
    HMODULE hi = GetModuleHandleW(nullptr);
    HRSRC r = FindResourceW(hi, MAKEINTRESOURCEW(id), RT_RCDATA);
    HGLOBAL g = r ? LoadResource(hi, r) : nullptr;
    const char* p = g ? (const char*)LockResource(g) : nullptr;
    DWORD size = r ? SizeofResource(hi, r) : 0;
    return (p && size) ? std::string(p, size) : std::string();
}

static std::wstring LangFile()
{
    wchar_t local[MAX_PATH];
    if (FAILED(SHGetFolderPathW(nullptr, CSIDL_LOCAL_APPDATA, nullptr, SHGFP_TYPE_CURRENT, local))) return L"";
    std::wstring root = std::wstring(local) + L"\\Indomitus Launcher";
    CreateDirectoryW(root.c_str(), nullptr);
    return root + L"\\language.txt";
}

static int LangIndex(const std::wstring& code)
{
    for (int i = 0; i < kLangCount; ++i) if (_wcsnicmp(code.c_str(), kLangs[i].code, 2) == 0) return i;
    return -1;
}

static void SetLanguage(int idx, bool persist)
{
    if (idx < 0 || idx >= kLangCount) idx = 0;
    g_lang = idx;
    g_langCur = ParseKvText(ResourceText(kLangs[idx].resId));
    if (persist) {
        std::wstring f = LangFile();
        if (!f.empty()) {
            std::string u = Utf8(kLangs[idx].code);
            HANDLE h = CreateFileW(f.c_str(), GENERIC_WRITE, 0, nullptr, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, nullptr);
            if (h != INVALID_HANDLE_VALUE) { DWORD w; WriteFile(h, u.data(), (DWORD)u.size(), &w, nullptr); CloseHandle(h); }
        }
    }
    Log(L"language: %ls", kLangs[idx].code);
}

struct LangMeta { std::wstring name, font; bool rtl = false; };
static LangMeta g_langMeta[sizeof(kLangs) / sizeof(kLangs[0])];

static void InitLanguage()
{
    for (int i = 0; i < kLangCount; ++i) {
        for (const auto& kv : ParseKvText(ResourceText(kLangs[i].resId))) {
            if (!_wcsicmp(kv.first.c_str(), L"name")) g_langMeta[i].name = kv.second;
            else if (!_wcsicmp(kv.first.c_str(), L"font")) g_langMeta[i].font = kv.second;
            else if (!_wcsicmp(kv.first.c_str(), L"rtl")) g_langMeta[i].rtl = kv.second == L"1";
        }
        if (g_langMeta[i].name.empty()) g_langMeta[i].name = kLangs[i].code;
    }
    g_langEn = ParseKvText(ResourceText(kLangs[0].resId));
    int idx = -1;
    std::wstring f = LangFile();
    if (!f.empty()) { std::string saved = ReadFileA(f); if (!saved.empty()) idx = LangIndex(Widen(saved)); }
    if (idx < 0) {
        wchar_t loc[LOCALE_NAME_MAX_LENGTH] = L"";
        GetUserDefaultLocaleName(loc, LOCALE_NAME_MAX_LENGTH);
        idx = LangIndex(loc);
    }
    SetLanguage(idx < 0 ? 0 : idx, false);
}

static std::wstring T(const wchar_t* key)
{
    for (const auto& kv : g_langCur) if (_wcsicmp(kv.first.c_str(), key) == 0 && !kv.second.empty()) return kv.second;
    for (const auto& kv : g_langEn)  if (_wcsicmp(kv.first.c_str(), key) == 0) return kv.second;
    return std::wstring(L"[") + key + L"]";
}

// ================================================================ Steam lookup

static std::wstring RegString(HKEY root, const wchar_t* sub, const wchar_t* name)
{
    wchar_t buf[MAX_PATH];
    DWORD size = sizeof(buf);
    if (RegGetValueW(root, sub, name, RRF_RT_REG_SZ, nullptr, buf, &size) == ERROR_SUCCESS) return buf;
    return L"";
}

static std::vector<std::string> VdfValues(const std::string& text, const std::string& key)
{
    std::vector<std::string> out;
    std::string needle = "\"" + key + "\"";
    size_t pos = 0;
    while ((pos = text.find(needle, pos)) != std::string::npos) {
        pos += needle.size();
        size_t q1 = text.find('"', pos);
        if (q1 == std::string::npos) break;
        size_t q2 = text.find('"', q1 + 1);
        if (q2 == std::string::npos) break;
        out.push_back(text.substr(q1 + 1, q2 - q1 - 1));
        pos = q2 + 1;
    }
    return out;
}

static std::string ReadFileA(const std::wstring& path)
{
    std::ifstream f(std::filesystem::path(path), std::ios::binary);
    if (!f) return "";
    return std::string((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
}

static bool FindFileRecursive(const std::wstring& dir, const wchar_t* name, int depth, std::wstring& found)
{
    if (depth < 0) return false;
    std::wstring direct = dir + L"\\" + name;
    if (PathFileExistsW(direct.c_str())) { found = direct; return true; }

    WIN32_FIND_DATAW fd;
    HANDLE h = FindFirstFileW((dir + L"\\*").c_str(), &fd);
    if (h == INVALID_HANDLE_VALUE) return false;
    bool ok = false;
    do {
        if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY)) continue;
        if (!wcscmp(fd.cFileName, L".") || !wcscmp(fd.cFileName, L"..")) continue;
        if (FindFileRecursive(dir + L"\\" + fd.cFileName, name, depth - 1, found)) { ok = true; break; }
    } while (FindNextFileW(h, &fd));
    FindClose(h);
    return ok;
}

static std::wstring FindGameExe(const std::wstring& appid)
{
    std::wstring steam = RegString(HKEY_CURRENT_USER, L"Software\\Valve\\Steam", L"SteamPath");
    if (steam.empty()) steam = RegString(HKEY_LOCAL_MACHINE, L"SOFTWARE\\WOW6432Node\\Valve\\Steam", L"InstallPath");
    if (steam.empty()) return L"";
    for (auto& c : steam) if (c == L'/') c = L'\\';

    std::vector<std::wstring> libs = { steam };
    std::string vdf = ReadFileA(steam + L"\\steamapps\\libraryfolders.vdf");
    for (const auto& p : VdfValues(vdf, "path")) {
        std::wstring w = Widen(p), clean;
        for (size_t i = 0; i < w.size(); ++i) {
            if (w[i] == L'\\' && i + 1 < w.size() && w[i + 1] == L'\\') ++i;
            clean += w[i];
        }
        libs.push_back(clean);
    }

    for (const auto& lib : libs) {
        std::string text = ReadFileA(lib + L"\\steamapps\\appmanifest_" + appid + L".acf");
        if (text.empty()) continue;
        auto dirs = VdfValues(text, "installdir");
        if (dirs.empty()) continue;
        std::wstring gameDir = lib + L"\\steamapps\\common\\" + Widen(dirs[0]);
        std::wstring exe;
        if (FindFileRecursive(gameDir, L"call_to_arms.exe", 3, exe)) return exe;
    }
    return L"";
}

// ================================================================ sealed payload
//
// The build script embeds every file in launcher\payload\ as RCDATA 501.. and a manifest
// (RCDATA 500, lines "id|name|sha256"). At launch the files are written to
// %LocalAppData%\Indomitus Launcher\payload\<fingerprint>\, re-hashed and refused on any
// mismatch. The .dll entries, in manifest order, are the only DLLs this launcher injects.

enum { RES_PAYLOAD_MANIFEST = 500 };

static std::string Sha256Hex(const void* data, size_t len)
{
    BCRYPT_ALG_HANDLE alg = nullptr; BCRYPT_HASH_HANDLE h = nullptr;
    std::string out;
    if (BCryptOpenAlgorithmProvider(&alg, BCRYPT_SHA256_ALGORITHM, nullptr, 0) < 0) return out;
    if (BCryptCreateHash(alg, &h, nullptr, 0, nullptr, 0, 0) >= 0) {
        UCHAR digest[32];
        if (BCryptHashData(h, (PUCHAR)data, (ULONG)len, 0) >= 0 && BCryptFinishHash(h, digest, 32, 0) >= 0) {
            static const char* hx = "0123456789abcdef";
            for (UCHAR c : digest) { out += hx[c >> 4]; out += hx[c & 15]; }
        }
        BCryptDestroyHash(h);
    }
    BCryptCloseAlgorithmProvider(alg, 0);
    return out;
}

struct PayloadEntry { int id; std::wstring name; std::string sha; };

static int g_manifestBad = 0;   // malformed manifest lines (bad hash from certutil, etc.)

static std::vector<PayloadEntry> ReadPayloadManifest()
{
    std::vector<PayloadEntry> out;
    g_manifestBad = 0;
    HMODULE hi = GetModuleHandleW(nullptr);
    HRSRC r = FindResourceW(hi, MAKEINTRESOURCEW(RES_PAYLOAD_MANIFEST), RT_RCDATA);
    if (!r) return out;
    HGLOBAL g = LoadResource(hi, r);
    const char* p = g ? (const char*)LockResource(g) : nullptr;
    DWORD size = SizeofResource(hi, r);
    if (!p || !size) return out;
    std::string text(p, size);
    size_t pos = 0;
    while (pos < text.size()) {
        size_t nl = text.find('\n', pos); if (nl == std::string::npos) nl = text.size();
        std::string line = text.substr(pos, nl - pos); pos = nl + 1;
        while (!line.empty() && (line.back() == '\r' || line.back() == ' ')) line.pop_back();
        size_t a = line.find('|'), b = line.rfind('|');
        if (line.empty() || a == std::string::npos || b == a) continue;
        PayloadEntry e;
        e.id = atoi(line.substr(0, a).c_str());
        e.name = Widen(line.substr(a + 1, b - a - 1));
        e.sha = line.substr(b + 1);
        for (auto& c : e.sha) c = (char)tolower((unsigned char)c);
        bool hex = e.sha.size() == 64;
        for (char c : e.sha) if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f'))) hex = false;
        if (e.id > 0 && !e.name.empty() && hex) out.push_back(e);
        else { ++g_manifestBad; Log(L"payload manifest: bad line '%hs'", line.c_str()); }
    }
    return out;
}

static bool WriteFileA(const std::wstring& path, const std::string& data);

// Returns false (after Fail) when the payload is missing or corrupt. Fills cfg.dlls/payloadDir/fingerprint.
static bool ExtractPayload(Config& cfg)
{
    std::vector<PayloadEntry> entries = ReadPayloadManifest();
#ifndef DEV_BUILD
    if (g_manifestBad) {
        Fail(1, L"The launcher's embedded file list is damaged (%d bad entr%ls).\nRebuild the launcher.", g_manifestBad, g_manifestBad == 1 ? L"y" : L"ies");
        return false;
    }
#endif
    if (entries.empty()) {
#ifdef DEV_BUILD
        Log(L"dev build: no embedded payload");
        cfg.fingerprint = L"dev";
        return true;
#else
        Fail(1, L"This launcher has no embedded payload - it was built without launcher\\payload\\ files.");
        return false;
#endif
    }
    std::string all;
    for (const auto& e : entries) all += e.sha;
    std::string fp = Sha256Hex(all.data(), all.size()).substr(0, 8);
    cfg.fingerprint = Widen(fp);

    wchar_t local[MAX_PATH];
    if (FAILED(SHGetFolderPathW(nullptr, CSIDL_LOCAL_APPDATA, nullptr, SHGFP_TYPE_CURRENT, local))) { Fail(1, L"LocalAppData not available."); return false; }
    std::wstring root = std::wstring(local) + L"\\Indomitus Launcher";
    cfg.payloadDir = root + L"\\payload\\" + cfg.fingerprint;
    CreateDirectoryW(root.c_str(), nullptr);
    CreateDirectoryW((root + L"\\payload").c_str(), nullptr);
    CreateDirectoryW(cfg.payloadDir.c_str(), nullptr);

    HMODULE hi = GetModuleHandleW(nullptr);
    for (const auto& e : entries) {
        HRSRC r = FindResourceW(hi, MAKEINTRESOURCEW(e.id), RT_RCDATA);
        HGLOBAL g = r ? LoadResource(hi, r) : nullptr;
        const char* p = g ? (const char*)LockResource(g) : nullptr;
        DWORD size = r ? SizeofResource(hi, r) : 0;
        if (!p || !size) { Fail(1, L"Embedded file missing: %ls", e.name.c_str()); return false; }
        if (Sha256Hex(p, size) != e.sha) { Fail(1, L"Embedded file is corrupt: %ls", e.name.c_str()); return false; }
        std::wstring dst = cfg.payloadDir + L"\\" + e.name;
        // always rewrite, so edits to extracted inis/dlls never survive a launch
        if (!WriteFileA(dst, std::string(p, size))) { Fail(1, L"Could not write %ls\n(is the game still running?)", dst.c_str()); return false; }
        std::string back = ReadFileA(dst);
        if (Sha256Hex(back.data(), back.size()) != e.sha) { Fail(1, L"Verification failed for %ls", dst.c_str()); return false; }
        size_t dot = e.name.rfind(L'.');
        if (dot != std::wstring::npos && _wcsicmp(e.name.c_str() + dot, L".dll") == 0) cfg.dlls.push_back(dst);
        Log(L"payload: %ls  %hs", e.name.c_str(), e.sha.substr(0, 12).c_str());
    }
    Log(L"payload fingerprint %ls, %u dll(s) in %ls", cfg.fingerprint.c_str(), (unsigned)cfg.dlls.size(), cfg.payloadDir.c_str());
    return true;
}

